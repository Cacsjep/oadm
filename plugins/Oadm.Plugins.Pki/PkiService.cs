/// <summary>Options of the PKI service (tests shorten the key and replace the clock and the trust store).</summary>
public sealed class PkiOptions
{
    /// <summary>RSA key size of generated CAs (tests use 2048 for speed).</summary>
    public int CaKeySize { get; init; } = PkiPluginInfo.CaKeySize;

    public TimeProvider Time { get; init; } = TimeProvider.System;

    /// <summary>For the default common name "OADM Root CA &lt;server name&gt;".</summary>
    public string ServerName { get; init; } = Environment.MachineName;

    /// <summary>The server's machine root store; null = the installer of the server OS.</summary>
    public ITrustStoreInstaller? TrustStore { get; init; }

    /// <summary>New issued certificates are written at most this often (tests: shorter).</summary>
    public TimeSpan IssuedFlushDelay { get; init; } = TimeSpan.FromSeconds(2);

    /// <summary>The pages hear of new issued certificates at most this often (tests: zero, at once).</summary>
    public TimeSpan CertificatesEventDelay { get; init; } = TimeSpan.FromSeconds(1);

    /// <summary>The one pass that reads the certificates of every device starts this long after the plugin (tests: zero).</summary>
    public TimeSpan ExistingImportDelay { get; init; } = TimeSpan.FromMinutes(5);

    /// <summary>The pass runs again this long after a round that reached no device (all offline, or the list not read yet).</summary>
    public TimeSpan ExistingImportRetry { get; init; } = TimeSpan.FromHours(1);

    /// <summary>Revoke all of this device reads the device's certificate list for at most this long first.</summary>
    public TimeSpan DeviceReadTimeout { get; init; } = TimeSpan.FromSeconds(20);

    /// <summary>
    /// How long a device must keep answering over HTTP after Disable HTTPS before Verify passes (its web server restarts a
    /// few seconds after the change; <see cref="Tasks.CertificateDeployment.FollowWebServerAsync"/>).
    /// </summary>
    public TimeSpan WebServerSettle { get; init; } = Tasks.CertificateDeployment.DefaultWebServerSettle;
}

/// <summary>
