    /// <summary>
    /// The page status (decision 2026-10-26: no OADM CA, the CA rows show their own state): it says only that the server
    /// cannot keep a CA, that the first-start CA is being made or could not be made; else the first-start CA's validity.
    /// </summary>
    public static ServiceStatus StatusOf(bool unavailable, bool generating, string? generationError, CaMaterial? ca, DateTime nowUtc, int warningDays)
    {
        if (unavailable)
        {
            return new ServiceStatus(ServiceStatus.Error, "CA cannot be stored on this server", "This server cannot store the CA key safely.");
        }

        if (generating)
        {
            return new ServiceStatus("accent", "Creating the certificate authority");
        }

        if (ca is null)
        {
            return generationError is null
                ? new ServiceStatus(ServiceStatus.Neutral, "No certificate authority")
                : new ServiceStatus(ServiceStatus.Error, "No certificate authority", generationError);
        }

        if (!ca.HasKey)
        {
            return new ServiceStatus(ServiceStatus.Error, "CA key cannot be read", "The CA was stored with another master key.");
        }

        var notAfter = ca.Certificate.NotAfter.ToUniversalTime();
        if (nowUtc > notAfter)
        {
            return new ServiceStatus(ServiceStatus.Error, "CA expired", $"Expired on {notAfter:yyyy-MM-dd}.");
        }

        var days = (int)Math.Floor((notAfter - nowUtc).TotalDays);
        if (days <= warningDays)
        {
            var text = days switch
            {
                0 => "CA expires today",
                1 => "CA expires in 1 day",
                _ => string.Create(CultureInfo.InvariantCulture, $"CA expires in {days} days"),
            };
            return new ServiceStatus(ServiceStatus.Warning, text, $"Valid until {notAfter:yyyy-MM-dd}.");
        }

        return new ServiceStatus(ServiceStatus.Ok, string.Create(CultureInfo.InvariantCulture, $"CA valid until {notAfter:yyyy-MM-dd}"));
    }

    /// <summary>
    /// Create CA (decision 2026-10-26): a root CA, or an intermediate signed by a listed CA with its key. The new CA joins the
    /// list like an imported CA with its key (its key encrypted with the master key, never logged) and can issue at once.
    /// Field errors under the fields; nothing is stored on a refusal.
    /// </summary>
    public async Task<PkiReply> CreateAuthorityAsync(CreateCaRequest request, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (Unavailable)
        {
            return await ErrorAsync("The CA cannot be stored on this server.", ct).ConfigureAwait(false);
        }

        var errors = new Dictionary<string, string>(StringComparer.Ordinal);
        Add(errors, PkiFields.CommonName, PkiValidation.CommonName(request.CommonName));
        Add(errors, PkiFields.ValidityYears, PkiValidation.ValidityYears(request.ValidityYears));
        Add(errors, PkiFields.Key, request.Key is { } key && CaKeys.All.Contains(key, StringComparer.Ordinal) ? null : "Choose a key.");
        CaMaterial? issuer = null;
        if (request.Intermediate)
        {
            issuer = IssuingCa(request.IssuerId);
            if (issuer is null)
            {
                errors[PkiFields.Issuer] = "Choose a CA with its key.";
            }
            else if (issuer.Certificate.NotAfter.ToUniversalTime() <= Now.UtcDateTime)
            {
                errors[PkiFields.Issuer] = "This CA has expired.";
            }
            else if (CaGenerator.CannotSignCa(issuer.Certificate) is { } cannot)
            {
                errors[PkiFields.Issuer] = cannot;
            }
        }

        if (!errors.ContainsKey(PkiFields.CommonName) && Authorities().Any(a => string.Equals(a.Name, request.CommonName!.Trim(), StringComparison.OrdinalIgnoreCase)))
        {
            errors[PkiFields.CommonName] = "Another CA has this name.";
        }

        if (errors.Count > 0)
        {
            return new PkiReply { Errors = errors };
        }

        if (_imported.Count >= PkiPluginInfo.MaxImportedCas)
        {
            return new PkiReply { Errors = One(PkiFields.CommonName, $"At most {PkiPluginInfo.MaxImportedCas} CAs can be created or imported. Delete one first.") };
        }

        var now = Now;
        var keyChoice = request.Key!;
        var material = await Task.Run(() => CaGenerator.Generate(request.CommonName!, null, request.ValidityYears, now, keyChoice, issuer), ct).ConfigureAwait(false);
        await _gate.WaitAsync(ct).ConfigureAwait(false);
        try
        {
            var entry = new StoredImportedCa
            {
                Id = material.Id,
                CertificatePem = material.CertificatePem,
                ChainPem = material.ChainPem,
                KeyProtected = _secrets!.Protect(material.KeyPkcs8Pem!, KeyPurposePrefix + material.Id),
                ImportedUtc = now.UtcDateTime,
                Created = true,
            };
            var list = new List<StoredImportedCa>(_imported) { entry };
            await _store.SaveImportedAsync(list, ct).ConfigureAwait(false);
            _importedMaterial = new Dictionary<string, CaMaterial>(_importedMaterial, StringComparer.OrdinalIgnoreCase) { [material.Id] = material };
            _imported = list;
            ApplyAnchors();
            LogCreated(material.Certificate.Subject, issuer?.Certificate.Subject ?? "itself", material.Certificate.NotAfter);
        }
        finally
        {
            _gate.Release();
        }

        CaChanged?.Invoke(this, EventArgs.Empty);
        await PublishAsync().ConfigureAwait(false);
        return new PkiReply { Ok = true, State = await GetStateAsync(ct).ConfigureAwait(false) };
    }

    public async Task<PkiReply> ImportAsync(ImportRequest request, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (Unavailable)
        {
            return await ErrorAsync("The CA cannot be stored on this server.", ct).ConfigureAwait(false);
        }

        if (!TryDecode(request.FileBase64, out var file) || file.Length == 0)
        {
            return new PkiReply { Errors = One(PkiFields.File, file is { Length: 0 } && request.FileBase64 is { Length: > 0 } ? "The file cannot be read." : "Choose a file.") };
        }

        byte[]? keyFile = null;
        if (!string.IsNullOrEmpty(request.KeyFileBase64) && !TryDecode(request.KeyFileBase64, out keyFile))
        {
            return new PkiReply { Errors = One(PkiFields.KeyFile, "The key file cannot be read.") };
        }

        var result = CaImporter.Import(new CaImportInput(file, request.FileName, request.Password, keyFile, request.KeyPassword), Now, DefaultValidDays);
        if (result.Ca is not { } material)
        {
            return new PkiReply { Errors = result.Errors };
        }

        // Decision 2026-10-25: a CA with its key is added to the list (it can issue); it never replaces another CA.
        return await AddImportedAsync(material, ct).ConfigureAwait(false);
    }

    public FileReply ExportPublic(ExportRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);
        var ca = _ca;
        if (ca is null)
        {
            return new FileReply { Error = "There is no certificate authority yet." };
        }

        return Export(ca.Certificate, ca.Chain, request.Format);
    }

    /// <summary>
    /// The previous CAs (public parts, DER) for other plugins' certificate checks, newest first: each the CA certificate,
    /// then its chain; unreadable entries are left out. Read from the PEM once per list of previous CAs (the list is replaced
    /// on every change), so a caller may ask for every authentication. The arrays are shared: read only.
    /// </summary>
    public IReadOnlyList<IReadOnlyList<byte[]>> PreviousChains()
    {
        var previous = _previous;
        if (Volatile.Read(ref _previousChains) is { } cached && ReferenceEquals(cached.Source, previous))
        {
            return cached.Chains;
        }

        var chains = ReadChains(previous);
        Volatile.Write(ref _previousChains, new PreviousChainCache(previous, chains));
        return chains;
    }

    private static List<IReadOnlyList<byte[]>> ReadChains(IReadOnlyList<StoredPreviousCa> previousCas)
    {
        var chains = new List<IReadOnlyList<byte[]>>();
        foreach (var previous in previousCas)
        {
            try
            {
                var der = new List<byte[]>();
                foreach (var pem in previous.ChainPem.Prepend(previous.CertificatePem))
                {
                    foreach (var certificate in CaCertificates.ReadPemCertificates(pem))
                    {
                        using (certificate)
                        {
                            der.Add(certificate.RawData);
                        }
                    }
                }

                if (der.Count > 0)
                {
                    chains.Add(der);
                }
            }
            catch (Exception ex) when (ex is CryptographicException or FormatException)
            {
                // unreadable entries are not trusted
            }
        }

        return chains;
    }

    public FileReply ExportPrevious(ExportPreviousRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);
        var previous = _previous.FirstOrDefault(p => string.Equals(p.Id, request.Id, StringComparison.OrdinalIgnoreCase));
        if (previous is null)
        {
            return new FileReply { Error = "This previous CA no longer exists." };
        }

        var certificates = CaCertificates.ReadPemCertificates(previous.CertificatePem);
        var chain = previous.ChainPem.SelectMany(CaCertificates.ReadPemCertificates).ToList();
        try
        {
            return certificates.Count == 0 ? new FileReply { Error = "The certificate cannot be read." } : Export(certificates[0], chain, request.Format);
        }
        finally
        {
            foreach (var certificate in certificates.Concat(chain))
            {
                certificate.Dispose();
            }
        }
    }

    /// <summary>
    /// Back up of a CA with its key (<see cref="BackupRequest.Id"/>; none: the first-start root CA): PKCS#12 with certificate,
    /// chain and key, AES-256-CBC + SHA-256, 100,000 iterations. The password is never stored or logged.
    /// </summary>
    public FileReply Backup(BackupRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (PkiValidation.BackupPassword(request.Password) is { } passwordError)
        {
            return new FileReply { Errors = One(PkiFields.Password, passwordError) };
        }

        var ca = IssuingCa(request.Id);
        if (ca is null)
        {
            return new FileReply { Error = "OADM cannot read the key of this CA, so it cannot be backed up." };
        }

        using var withKey = ca.WithPrivateKey();
        var collection = new X509Certificate2Collection { withKey };
        foreach (var certificate in ca.Chain)
        {
            collection.Add(certificate);
        }

        var bytes = collection.ExportPkcs12(new PbeParameters(PbeEncryptionAlgorithm.Aes256Cbc, HashAlgorithmName.SHA256, 100_000), request.Password);
        LogBackup(ca.Certificate.Subject);
        return new FileReply { FileName = CaCertificates.FileNameFor(CaCertificates.CommonName(ca.Certificate), ".pfx"), DataBase64 = Convert.ToBase64String(bytes) };
    }

    /// <summary>Installs the first-start root CA into the server's machine root store.</summary>
    public Task<InstallReply> InstallServerTrustAsync(CancellationToken ct) => InstallServerTrustAsync(null, ct);

    /// <summary>
    /// Installs a root CA of the list (<see cref="InstallTrustRequest.Fingerprint"/>; none: the first-start root CA) into the
    /// server's machine root store (decision 2026-10-26: every root CA can be installed).
    /// </summary>
    public async Task<InstallReply> InstallServerTrustAsync(InstallTrustRequest? request, CancellationToken ct)
    {
        byte[]? der = null;
        if (request?.Fingerprint is { Length: > 0 } wanted)
        {
            der = Issuers().AuthorityRows.FirstOrDefault(r => r.Row.IsRootCa && string.Equals(CertificateFingerprint(r.Der), wanted, StringComparison.OrdinalIgnoreCase))?.Der;
        }
        else if (_ca is { } first && CaCertificates.IsSelfIssued(first.Certificate))
        {
            der = first.Certificate.RawData;
        }

        if (der is null)
        {
            return new InstallReply(false, "This root CA is no longer in the list.", await GetStateAsync(ct).ConfigureAwait(false));
        }

        using var certificate = X509CertificateLoader.LoadCertificate(der);
        var fingerprint = CertificateFingerprint(der);
        TrustStoreResult result;
        try
        {
            result = await _trustStore.InstallAsync(certificate, ct).ConfigureAwait(false);
        }
#pragma warning disable CA1031 // Shown on the page.
        catch (Exception ex) when (ex is not OperationCanceledException)
#pragma warning restore CA1031
        {
            result = new TrustStoreResult(false, ex.Message);
        }

        var errors = new Dictionary<string, string>(_serverTrustErrors, StringComparer.OrdinalIgnoreCase);
        if (result.Error is { } error)
        {
            errors[fingerprint] = error;
        }
        else
        {
            errors.Remove(fingerprint);
        }

        _serverTrustErrors = errors;
        if (result.Installed)
        {
            LogTrustInstalled(certificate.Subject);
        }
        else
        {
            LogTrustFailed(certificate.Subject, result.Error ?? string.Empty);
        }

        await PublishAsync().ConfigureAwait(false);
        return new InstallReply(result.Installed, result.Error, await GetStateAsync(ct).ConfigureAwait(false));
    }

    /// Device certificate validity for a certificate issued now: <paramref name="days"/> (an issuing policy's; null: the first
    /// HTTPS certificate policy's, else 365), shortened to the end of validity of the CA that signs (<paramref name="issuer"/>;
    /// null: the OADM CA), logged.
    /// </summary>
    public TimeSpan DeviceCertificateValidity(int? days = null, CaMaterial? issuer = null)
    {
        var validDays = days ?? DefaultValidDays;
        var wanted = TimeSpan.FromDays(validDays);
        if ((issuer ?? _ca) is not { } ca)
        {
            return wanted;
        }

        var left = ca.Certificate.NotAfter.ToUniversalTime() - Now.UtcDateTime;
        if (left < wanted)
        {
            var leftDays = Math.Max(0, (int)left.TotalDays);
            LogValidityShortened(validDays, leftDays);
            return left < TimeSpan.Zero ? TimeSpan.Zero : left;
        }

        return wanted;
    }

    private async Task GenerateDefaultAsync(CancellationToken ct)
    {
        try
        {
            await _gate.WaitAsync(ct).ConfigureAwait(false);
            try
            {
                if (_stored is not null)
                {
                    return;
                }

                var name = PkiPluginInfo.DefaultCommonName(_options.ServerName);
                var material = CaGenerator.Generate(name, null, PkiPluginInfo.DefaultValidityYears, Now, _options.CaKeySize);
                await ReplaceAsync(material, CaSource.Generated, ct).ConfigureAwait(false);
                var (subject, notAfter) = (material.Certificate.Subject, material.Certificate.NotAfter);
                LogDefaultGenerated(subject, notAfter);
            }
            finally
            {
                _generating = false;
                _gate.Release();
            }
        }
        catch (OperationCanceledException) when (ct.IsCancellationRequested)
        {
            _generating = false;
            return;
        }
#pragma warning disable CA1031 // Shown in the status line; the user can generate or import.
        catch (Exception ex)
#pragma warning restore CA1031
        {
            _generationError = "Creating the CA failed: " + ex.Message;
            LogGenerationFailed(ex);
        }

        await PublishAsync().ConfigureAwait(false);
    }

    /// <summary>
    /// The user deletes a stored CA that cannot be read: its stored value (<paramref name="raw"/>) is first written as it is
    /// to <c>ca-unreadable-&lt;UTC time&gt;.json</c> in <see cref="DataDirectory"/> for support (never logged), then it may be
    /// removed. False (nothing changed): no folder, or the file could not be written. Call inside the gate.
    /// </summary>
    private async Task<bool> KeepUnreadableCaAsync(string raw, CancellationToken ct)
    {
        if (DataDirectory is not { Length: > 0 } folder)
        {
            return false;
        }

        try
        {
            Directory.CreateDirectory(folder);
            var name = string.Create(CultureInfo.InvariantCulture, $"ca-unreadable-{Now.UtcDateTime:yyyyMMdd-HHmmss-fff}.json");
            var path = Path.Combine(folder, name);
            await File.WriteAllTextAsync(path, raw, ct).ConfigureAwait(false);
            LogUnreadableCaKept(name);
            return true;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            LogUnreadableCaNotKept(ex.GetType().Name);
            return false;
        }
    }

    /// <summary>The first-start root CA is stored and becomes the CA with the id "oadm" (the built-in policies name it). Call inside the gate.</summary>
    private async Task ReplaceAsync(CaMaterial material, string source, CancellationToken ct)
    {
        if (_caUnreadable)
        {
            throw new InvalidOperationException("The stored CA cannot be read."); // never written over a damaged stored CA
        }

        var stored = new StoredCa
        {
            Id = material.Id,
            Source = source,
            CertificatePem = material.CertificatePem,
            ChainPem = material.ChainPem,
            KeyProtected = _secrets!.Protect(material.KeyPkcs8Pem!, KeyPurposePrefix + material.Id),
            CreatedUtc = Now.UtcDateTime,
        };
        await _store.SaveCaAsync(stored, ct).ConfigureAwait(false);
        _stored = stored;
        _ca = material;
        _generationError = null;
        ApplyAnchors();
        CaChanged?.Invoke(this, EventArgs.Empty);
    }

    private CaMaterial? LoadMaterial(StoredCa stored)
    {
        List<X509Certificate2> certificates;
        try
        {
            certificates = CaCertificates.ReadPemCertificates(stored.CertificatePem);
        }
        catch (Exception ex) when (ex is CryptographicException or FormatException)
        {
            certificates = [];
        }

        if (certificates.Count == 0)
        {
            LogStoredCaUnreadable(stored.Id);
            return null;
        }

        var chain = new List<X509Certificate2>();
        foreach (var pem in stored.ChainPem)
        {
            try
            {
                chain.AddRange(CaCertificates.ReadPemCertificates(pem));
            }
            catch (Exception ex) when (ex is CryptographicException or FormatException)
            {
                // a damaged chain entry is left out
            }
        }

        string? key;
        try
        {
            key = _secrets!.Unprotect(stored.KeyProtected, KeyPurposePrefix + stored.Id);
        }
        catch (Exception ex) when (ex is CryptographicException or FormatException or ArgumentException)
        {
            key = null;
        }

        return new CaMaterial(certificates[0], chain, key);
    }

    /// <summary>The active CA with its chain and the previous CAs with theirs (public parts) for the server's own check.</summary>
    private void ApplyAnchors()
    {
        if (_anchors is null)
        {
            return;
        }

        var der = new List<byte[]>();
        if (_ca is { } ca)
        {
            der.Add(ca.Certificate.RawData);
            der.AddRange(ca.Chain.Select(c => c.RawData));
        }

        foreach (var previous in _previous)
        {
            foreach (var pem in previous.ChainPem.Prepend(previous.CertificatePem))
            {
                try
                {
                    foreach (var certificate in CaCertificates.ReadPemCertificates(pem))
                    {
                        using (certificate)
                        {
                            der.Add(certificate.RawData);
                        }
                    }
                }
                catch (Exception ex) when (ex is CryptographicException or FormatException)
                {
                    // unreadable entries are not trusted
                }
            }
        }

        // Every imported CA with its key issues device certificates too (decision 2026-10-25): the server trusts them and
        // their chains like the OADM CA's. Imported certificates without a key stay out (as before).
        var issuing = _importedMaterial.Values.Where(m => m.HasKey).ToList();
        foreach (var imported in issuing)
        {
            der.Add(imported.Certificate.RawData);
            der.AddRange(imported.Chain.Select(c => c.RawData));
        }

        _anchors.Set(der);

        // Renewals are pinned again only for certificates the CAs of PKI themselves issued: the CAs, not their chains.
        var issuers = new List<byte[]>();
        if (_ca is { } active)
        {
            issuers.Add(active.Certificate.RawData);
        }

        issuers.AddRange(issuing.Select(m => m.Certificate.RawData));

        foreach (var previous in _previous)
        {
            try
            {
                using var certificate = CaCertificates.ReadPemCertificates(previous.CertificatePem).FirstOrDefault();
                if (certificate is not null)
                {
                    issuers.Add(certificate.RawData);
                }
            }
            catch (Exception ex) when (ex is CryptographicException or FormatException)
            {
                // unreadable entries are not trusted
            }
        }

        _anchors.SetRenewalIssuers(issuers);
    }

    private async Task<IReadOnlyList<StoredPreviousCa>> PrunePreviousAsync(List<StoredPreviousCa> previous, CancellationToken ct)
    {
        var now = Now.UtcDateTime;
        var kept = previous.Where(p => ReadNotAfter(p.CertificatePem) is not { } end || end > now).ToList();
        if (kept.Count != previous.Count)
        {
            await _store.SavePreviousAsync(kept, ct).ConfigureAwait(false);
            LogPreviousExpired(previous.Count - kept.Count);
        }

        return kept;
    }

    private async Task PublishAsync()
    {
        if (_events is null)
        {
            return;
        }

        try
        {
            _events.Publish(PkiMethods.StateTopic, PkiJson.Serialize(await GetStateAsync(CancellationToken.None).ConfigureAwait(false)), PluginEventAudience.AllDevices);

            // The pages of users limited to a group: the same state with the counts of their own devices.
            foreach (var key in Viewers.Keys())
            {
                var view = await ViewedSet.OfScopeAsync(Viewers.Scopes, key, CancellationToken.None).ConfigureAwait(false);
                _events.Publish(PkiMethods.StateTopic, PkiJson.Serialize(await GetStateAsync(view, CancellationToken.None).ConfigureAwait(false)), PluginEventAudience.DeviceScope(key));
            }
        }
#pragma warning disable CA1031 // Events are best effort; pages re-read the state.
        catch (Exception ex)
#pragma warning restore CA1031
        {
            LogPublishFailed(ex);
        }
    }

