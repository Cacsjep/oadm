    private static FileReply Export(X509Certificate2 certificate, IReadOnlyList<X509Certificate2> chain, string? format)
    {
        var name = CaCertificates.CommonName(certificate);
        switch (format?.ToLowerInvariant())
        {
            case "pem":
                var pem = new StringBuilder(CaCertificates.ToPem(certificate));
                foreach (var issuer in chain)
                {
                    pem.Append(CaCertificates.ToPem(issuer));
                }

                return new FileReply { FileName = CaCertificates.FileNameFor(name, ".crt"), DataBase64 = Convert.ToBase64String(Encoding.ASCII.GetBytes(pem.ToString())) };
            case "der":
                return new FileReply { FileName = CaCertificates.FileNameFor(name, ".cer"), DataBase64 = Convert.ToBase64String(certificate.RawData) };
            default:
                return new FileReply { Error = "Choose PEM (.crt) or DER (.cer)." };
        }
    }

    private static PreviousCaInfo DescribePrevious(StoredPreviousCa previous, IssuedCounts counts)
    {
        var info = new PreviousCaInfo { Id = previous.Id, ReplacedUtc = previous.ReplacedUtc, Devices = counts.DevicesPerCa.GetValueOrDefault(previous.Id) };
        try
        {
            var certificates = CaCertificates.ReadPemCertificates(previous.CertificatePem);
            if (certificates.Count > 0)
            {
                using var certificate = certificates[0];
                info = info with
                {
                    CommonName = CaCertificates.CommonName(certificate),
                    Subject = certificate.Subject,
                    NotAfterUtc = certificate.NotAfter.ToUniversalTime(),
                };
            }
        }
        catch (Exception ex) when (ex is CryptographicException or FormatException)
        {
            info = info with { CommonName = previous.Id };
        }

        return info;
    }

    private static DateTime? ReadNotAfter(string pem)
    {
        try
        {
            var certificates = CaCertificates.ReadPemCertificates(pem);
            if (certificates.Count == 0)
            {
                return null;
            }

            using var certificate = certificates[0];
            return certificate.NotAfter.ToUniversalTime();
        }
        catch (Exception ex) when (ex is CryptographicException or FormatException)
        {
            return null;
        }
    }

    internal static CertificateSummary? RadiusSummary(string? pem)
    {
        if (string.IsNullOrWhiteSpace(pem))
        {
            return null;
        }

        try
        {
            var certificates = CaCertificates.ReadPemCertificates(pem);
            if (certificates.Count == 0)
            {
                return null;
            }

            using var certificate = certificates[0];
            return CaCertificates.Summarize(certificate);
        }
        catch (Exception ex) when (ex is CryptographicException or FormatException)
        {
            return null;
        }
    }

    private static bool TryDecode(string? base64, out byte[] bytes)
    {
        bytes = [];
        if (string.IsNullOrEmpty(base64))
        {
            return false;
        }

        try
        {
            bytes = Convert.FromBase64String(base64);
            return true;
        }
        catch (FormatException)
        {
            return false;
        }
    }

